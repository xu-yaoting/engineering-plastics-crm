// Keep <html lang> in sync with the active UI language (zh → zh-CN, else en).
const syncDocumentLang = (lng: string) => {
  document.documentElement.lang = lng.startsWith('zh') ? 'zh-CN' : 'en';
};
syncDocumentLang(i18n.language || 'zh');

i18n.on('languageChanged', (lng) => {
  localStorage.setItem('crm-language', lng);
  syncDocumentLang(lng);
});

